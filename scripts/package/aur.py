#!/usr/bin/env python3
"""Write the AUR PKGBUILD and .SRCINFO of a release from its Linux archives.

Usage: aur.py --channel stable|nightly --version VERSION --dist DIR --output DIR
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

REPOSITORY = "https://github.com/vsevolodbazhan/qrow"
ARCHES = ("x86_64", "aarch64")
PACKAGES = {"stable": "qrow-desktop-bin", "nightly": "qrow-desktop-nightly-bin"}
DESCRIPTION = "Native SQL workbench"
DEPENDS = (
    "gcc-libs",
    "glibc",
    "libxcb",
    "libxkbcommon",
    "libxkbcommon-x11",
    "vulkan-driver",
    "vulkan-icd-loader",
    "wayland",
)
OPTDEPENDS = ("org.freedesktop.secrets: save passwords and sign-ins",)
# Both packages install /usr/bin/qrow, and so does the unrelated `qrow` package.
CONFLICTS = ("qrow", "qrow-bin", "qrow-desktop", *PACKAGES.values())
RELEASE_VERSION = re.compile(r"[0-9A-Za-z][0-9A-Za-z.+-]*")


def pkgver(version: str) -> str:
    """Return a pacman version: release versions may contain `-` and `+`."""
    return re.sub(r"[-+]", ".", version)


def archive(version: str, arch: str) -> str:
    return f"Qrow-{version}-linux-{arch}.tar.gz"


def quoted(values: tuple[str, ...]) -> str:
    return " ".join(f"'{value}'" for value in values)


def conflicts(pkgname: str) -> tuple[str, ...]:
    return tuple(name for name in CONFLICTS if name != pkgname)


def pkgbuild(pkgname: str, version: str, digests: dict[str, str]) -> str:
    sources = "\n".join(
        f'source_{arch}=("{archive("${_tag}", arch)}::'
        f'${{url}}/releases/download/v${{_tag}}/{archive("${_tag}", arch)}")'
        for arch in ARCHES
    )
    sums = "\n".join(f"sha256sums_{arch}=('{digests[arch]}')" for arch in ARCHES)
    return f"""# Maintainer: Vsevolod Bazhan <{REPOSITORY}>
# Generated by scripts/package/aur.py in {REPOSITORY}. Do not edit.

pkgname={pkgname}
_tag={version}
pkgver={pkgver(version)}
pkgrel=1
pkgdesc="{DESCRIPTION}"
arch=({quoted(ARCHES)})
url="{REPOSITORY}"
license=('MIT')
depends=({quoted(DEPENDS)})
optdepends=({quoted(OPTDEPENDS)})
provides=('qrow-desktop')
conflicts=({quoted(conflicts(pkgname))})
options=('!strip' '!debug')
{sources}
{sums}

package() {{
  install -Dm755 bin/qrow "$pkgdir/usr/bin/qrow"
  install -Dm644 share/applications/qrow.desktop "$pkgdir/usr/share/applications/qrow.desktop"
  install -Dm644 share/icons/hicolor/256x256/apps/qrow.png \\
    "$pkgdir/usr/share/icons/hicolor/256x256/apps/qrow.png"
  install -Dm644 -t "$pkgdir/usr/share/licenses/$pkgname" share/licenses/qrow/*
}}
"""


def srcinfo(pkgname: str, version: str, digests: dict[str, str]) -> str:
    """Return the .SRCINFO that `makepkg --printsrcinfo` writes for `pkgbuild`."""
    lines = [
        f"pkgbase = {pkgname}",
        f"\tpkgdesc = {DESCRIPTION}",
        f"\tpkgver = {pkgver(version)}",
        "\tpkgrel = 1",
        f"\turl = {REPOSITORY}",
        *(f"\tarch = {arch}" for arch in ARCHES),
        "\tlicense = MIT",
        *(f"\tdepends = {name}" for name in DEPENDS),
        *(f"\toptdepends = {name}" for name in OPTDEPENDS),
        "\tprovides = qrow-desktop",
        *(f"\tconflicts = {name}" for name in conflicts(pkgname)),
        "\toptions = !strip",
        "\toptions = !debug",
    ]
    for arch in ARCHES:
        name = archive(version, arch)
        lines.append(f"\tsource_{arch} = {name}::{REPOSITORY}/releases/download/v{version}/{name}")
        lines.append(f"\tsha256sums_{arch} = {digests[arch]}")
    return "\n".join([*lines, "", f"pkgname = {pkgname}", ""])


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        while chunk := file.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def write(channel: str, version: str, dist: Path, output: Path) -> Path:
    """Write the package of the channel into `output/<pkgname>` and return that directory."""
    if channel not in PACKAGES:
        raise ValueError(f"Unknown release channel: {channel!r}")
    if not RELEASE_VERSION.fullmatch(version):
        raise ValueError(f"Invalid release version: {version!r}")
    digests = {}
    for arch in ARCHES:
        path = dist / archive(version, arch)
        if not path.is_file():
            raise ValueError(f"Missing Linux archive: {path}")
        digests[arch] = sha256(path)
    pkgname = PACKAGES[channel]
    directory = output / pkgname
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "PKGBUILD").write_text(pkgbuild(pkgname, version, digests))
    (directory / ".SRCINFO").write_text(srcinfo(pkgname, version, digests))
    return directory


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--channel", required=True, choices=sorted(PACKAGES))
    parser.add_argument("--version", required=True)
    parser.add_argument("--dist", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    arguments = parser.parse_args()
    try:
        print(write(arguments.channel, arguments.version, arguments.dist, arguments.output))
    except ValueError as error:
        parser.exit(1, f"error: {error}\n")


if __name__ == "__main__":
    main()
